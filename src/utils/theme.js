export function applyTheme(theme) {
  if (!theme || !theme.colors) return;
  Object.entries(theme.colors).forEach(([k, v]) => {
    document.documentElement.style.setProperty(k, v);
  });
  // 适配 element-plus 主题色
  // 主色、悬停、激活、文字色等
  const elMap = [
    ['--el-color-primary', theme.colors['--button'] || '#409eff'],
    ['--el-color-primary-light-3', theme.colors['--button-hover'] || '#79bbff'],
    ['--el-color-primary-dark-2', theme.colors['--button-active'] || '#337ecc'],
    ['--el-color-primary-text', theme.colors['--button-text'] || '#fff'],
    ['--el-text-color-primary', theme.colors['--main-text'] || '#222'],
    ['--el-bg-color', theme.colors['--bg-main'] || '#fff'],
    ['--el-border-color', theme.colors['--input-border'] || '#dcdfe6'],
    ['--el-input-bg-color', theme.colors['--input-bg'] || '#fff'],
    ['--el-color-success', '#67c23a'],
    ['--el-color-warning', '#e6a23c'],
    ['--el-color-danger', '#f56c6c'],
    ['--el-color-info', '#909399'],
  ];
  elMap.forEach(([k, v]) => {
    document.documentElement.style.setProperty(k, v);
  });
}
